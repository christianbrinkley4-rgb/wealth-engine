const PATH = "/medicare-nc-history";
const UPDATED = "2026-11-04";

const S0 = state(FIRST_YEAR);
const S1 = state(LAST_YEAR);
const LOW = lowestMoopYear();
const SLOW = state(LOW);
const MOOP_RISE = (S1.moopMedian ?? 0) - (SLOW.moopMedian ?? 0);
const MOOP_PCT = percentChange(SLOW.moopMedian ?? 1, S1.moopMedian ?? 0);
const PDP_PCT = percentChange(S0.pdpPlans, S1.pdpPlans);
const G0 = county("Guilford", FIRST_YEAR)!;
const G1 = county("Guilford", LAST_YEAR)!;
const ZERO_PDP_YEARS = HISTORY_YEARS.filter((y) => state(y).pdpZeroPremium > 0);

const TITLE = "NC Medicare Advantage 2022-2027: Six Years of County Data";
const DESCRIPTION = `How Medicare Advantage changed in North Carolina from ${FIRST_YEAR} to ${LAST_YEAR}: plan counts, $0-premium plans and out-of-pocket limits for all 100 counties, from CMS data.`;

