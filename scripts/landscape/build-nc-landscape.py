"""Build lib/ncLandscape2027.ts from the CMS Medicare Advantage/Part D Landscape files.

Usage: python3 scripts/landscape/build-nc-landscape.py CY2027_Landscape.csv CY2026_Landscape.csv lib/ncLandscape2027.ts
Download the zips from https://www.cms.gov/medicare/coverage/prescription-drug-coverage (Landscape Source Files).
"""
import csv, json, statistics
def money(s):
    s=(s or '').strip().replace('$','').replace(',','')
    if s.startswith('(') and s.endswith(')'): s='-'+s[1:-1]
    try: return float(s)
    except: return None
def load(path, year):
    with open(path, newline='', encoding='utf-8-sig') as fh:
        rows=[x for x in csv.DictReader(fh) if x['State Territory Abbreviation']=='NC']
    return rows
import sys
r27=load(sys.argv[1],2027)
r26=load(sys.argv[2],2026)
def seg(x): return x.get('Contract Plan Segment ID') or x.get('ContractPlanSegmentID')
def general_ma(rows):  # non-SNP MA and MA-PD
    return [x for x in rows if x['Contract Category Type'] in ('MA','MA-PD') and x['Special Needs Plan (SNP) Indicator']!='Yes']
def stats(rows):
    g=general_ma(rows)
    mapd=[x for x in g if x['Contract Category Type']=='MA-PD']
    zero=[x for x in mapd if money(x['Monthly Consolidated Premium (Part C + D)'])==0]
    moops=[money(x['In-Network Maximum Out-of-Pocket (MOOP) Amount']) for x in g]
    moops=[m for m in moops if m]
    ppo=[x for x in g if 'PPO' in x['Plan Type']]
    hmo=[x for x in g if 'HMO' in x['Plan Type']]
    stars=[x for x in g if (x['Overall Star Rating'] or '').replace('.','',1).isdigit() and float(x['Overall Star Rating'])>=4]
    snp=[x for x in rows if x['Special Needs Plan (SNP) Indicator']=='Yes' and x['Contract Category Type'] in ('SNP','MA','MA-PD')]
    return dict(plans=len(g), withDrugs=len(mapd), zeroPremium=len(zero), ppo=len(ppo), hmo=len(hmo),
        moopMin=min(moops) if moops else None, moopMedian=statistics.median(moops) if moops else None,
        fourStarPlus=len(stars), insurers=len(set(x['Parent Organization Name'] for x in g)), specialNeeds=len(snp))
counties=sorted(set(x['County Name'] for x in r27+r26 if x['County Name']!='All Counties'))
out={}
for c in counties:
    a=[x for x in r27 if x['County Name']==c]; b=[x for x in r26 if x['County Name']==c]
    s27=stats(a); s26=stats(b)
    ids27=set(seg(x) for x in general_ma(a)); ids26=set(seg(x) for x in general_ma(b))
    out[c]={'y2027':s27,'y2026':s26,'notOfferedFor2027':len(ids26-ids27),'newFor2027':len(ids27-ids26)}
# PDP statewide
def pdp(rows):
    p=[x for x in rows if x['Contract Category Type']=='PDP']
    zero=[x for x in p if money(x['Part D Total Premium'])==0]
    prem=[money(x['Part D Total Premium']) for x in p]; prem=[v for v in prem if v is not None]
    return dict(plans=len(p), zeroPremium=len(zero), lowestPremium=min(prem) if prem else None, insurers=len(set(x['Parent Organization Name'] for x in p)))
import json
def ts(o): return json.dumps(o, separators=(',', ':'))
lines=['// GENERATED by scripts/landscape/build-nc-landscape.py from the CMS CY2027 Landscape',
'// (data updated 10/18/2026) and CY2026 Landscape (09/2026) files. Do not edit by hand.',
'// Counts only: no plan or insurer names. Excludes Special Needs Plans and employer plans.',
'import type { NcLandscape } from "./ncLandscapeTypes";','',
'export const NC_LANDSCAPE: NcLandscape = '+ts({'dataUpdated':'2026-10-18','counties':out,'pdp':{'y2027':pdp(r27),'y2026':pdp(r26)}})+';','']
open(sys.argv[3],'w').write('\n'.join(lines))
print('wrote', sys.argv[3], len(out), 'counties')
